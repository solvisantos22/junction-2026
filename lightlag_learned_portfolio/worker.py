"""Trusted evaluator and source fingerprints; simulator state never enters a policy."""

from collections import Counter
import hashlib
import json
from pathlib import Path
import pickle
import platform
import time
import traceback

from lightlag_traverse.environment import TraverseEnvironment
from lightlag_traverse_max.heldout import check_training_seeds
from .policy import play

ROOT = Path(__file__).resolve().parents[1]
QUICK = {"plan_steps": 12000, "replan_steps": 2000, "beam": 60, "rebeam": 20}


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def digest(value):
    return hashlib.sha256(canonical(value)).hexdigest()


def source_manifest():
    files = [ROOT / "docs/learned-portfolio.md", ROOT / "lightlag_traverse_max/heldout.py"]
    for package in ("lightlag", "lightlag_traverse", "lightlag_learned_portfolio"):
        files += sorted((ROOT / package).glob("*.py"))
    for name in ("cloud.py", "run.py"):
        files.append(ROOT / "tools/learned_portfolio" / name)
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(files)}


def run_episode(job, model=None):
    check_training_seeds([job["seed"]])
    if job.get("source") and job["source"] != source_manifest():
        raise ValueError("uploaded source differs from frozen source")
    env = TraverseEnvironment(job["seed"])
    calls, invalid = Counter(), []
    def invoke(name, *args):
        calls[name] += 1
        try:
            return getattr(env, name)(*args)
        except ValueError as error:
            invalid.append({"method": name, "error": str(error)})
            raise
    class Tools:
        def rules(self): return invoke("rules")
        def map(self): return invoke("map")
        def telemetry_log(self): return invoke("telemetry_log")
        def uplink(self, commands): return invoke("uplink", commands)
        def advance(self, ticks=1): return invoke("advance", ticks)
        def __getattr__(self, name): raise AssertionError("non-public attribute: " + name)
    started, cpu = time.perf_counter(), time.process_time()
    decision, error = None, None
    try:
        _, decision = play(Tools(), job["spec"], model, QUICK if job.get("quick") else None)
    except Exception:
        error = traceback.format_exc()
    seconds, cpu_seconds = time.perf_counter() - started, time.process_time() - cpu
    while not env.advance(1)["episode_complete"]:
        pass
    replay = env.replay()
    result = replay["result"]
    prefix = [c for c in replay["commands"] if c["sent_tick"] < 140]
    out = {"job": {k: v for k, v in job.items() if k != "source"}, "decision": decision,
           "result": result, "reward": result["raw_score"] / result["max_available_value"],
           "commands": replay["commands"], "replay_sha256": digest(replay), "prefix_sha256": digest(prefix),
           "calls": dict(calls), "invalid": invalid, "error": error,
           "seconds": seconds, "cpu_seconds": cpu_seconds,
           "python": platform.python_version(), "source_sha256": digest(source_manifest())}
    if job.get("keep_replay"):
        out["replay"] = replay
    return out


def load_model(path, expected_sha):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_sha:
        raise ValueError("model checkpoint hash mismatch")
    # Only checkpoints generated by this study are loaded, after their digest check.
    return pickle.loads(data)
