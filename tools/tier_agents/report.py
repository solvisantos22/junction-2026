#!/usr/bin/env python3
"""Tables for docs/tier-comparison.md, built only from saved files (nothing is run or asked).

    python3 tools/tier_agents/report.py > docs/tier-comparison/tables.md

Reads docs/lightlag-runs/ (Harbor agent runs: result.json; one-request runs: sandbox.json) and
docs/traverse-farm/*/evaluation.json (the replays on many worlds). Claude's numbers are
Kristján's runs, read the same way. Standard library only.
"""

from __future__ import annotations

import json
import re
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RUNS = REPO / "docs" / "lightlag-runs"
FARM = REPO / "docs" / "traverse-farm"
LEDGER = REPO / "docs" / "tier-comparison" / "runs.jsonl"
REFERENCE = {"campaign": 0.476257, "traverse": 0.564655}   # Harbor -a oracle (docs/lightlag-traverse-readiness.md)

LINEUP = [  # tier, (lab, name, run-name stem)
    ("Top", [("Anthropic", "Opus 5.5", "opus"), ("OpenAI", "GPT-6.1 Sol", "gpt-6.1-sol"), ("Google", "Gemini 4 Carbon", "gemini-4-carbon")]),
    ("Middle", [("Anthropic", "Sonnet 5.5", "sonnet"), ("OpenAI", "GPT-6.1 Terra", "gpt-6.1-terra"), ("Google", "Gemini 4 Argon", "gemini-4-argon")]),
    ("Bottom", [("Anthropic", "Haiku 5.5", "haiku"), ("OpenAI", "GPT-6 Luna", "gpt-6-luna"), ("Google", "Gemini 4 Hydrogen", "gemini-4-hydrogen")]),
]


def harbor_rewards(prefix: str, stem: str) -> list:
    out = []
    for folder in sorted(RUNS.glob("{}-{}-*".format(prefix, stem)), key=lambda p: int(p.name.rsplit("-", 1)[1])):
        if not re.fullmatch(re.escape("{}-{}-".format(prefix, stem)) + r"\d+", folder.name):
            continue
        result = json.loads((folder / "result.json").read_text())
        reward = ((result.get("verifier_result") or {}).get("rewards") or {}).get("reward")
        out.append(0.0 if reward is None else reward)
    return out


def oneshot(stem: str):
    folder = RUNS / "traverse-oneshot-{}-1".format(stem)
    if not (folder / "sandbox.json").exists():
        return None
    return json.loads((folder / "sandbox.json").read_text())["reward"]


def farm_means(folders: list) -> dict:
    """policy name -> (mean, worlds) from one or more farm evaluations; a later folder wins."""
    means = {}
    for name in folders:
        path = FARM / name / "evaluation.json"
        if path.exists():
            for policy, row in json.loads(path.read_text())["table"].items():
                means[policy] = (row["mean"], row["worlds"])
    return means


def cell(values: list) -> str:
    if not values:
        return "–"
    return "**{:.3f}** ({})".format(statistics.mean(values), ", ".join("{:.2f}".format(v) for v in values))


def costs() -> dict:
    by_model = {}
    if LEDGER.exists():
        for line in LEDGER.read_text().splitlines():
            row = json.loads(line)
            cost = row.get("cost_usd_reported_by_opencode") or row.get("cost_usd_from_prices") or 0
            by_model.setdefault(row["model"].split("/", 1)[1], []).append(cost)
    return by_model


def main() -> None:
    print("<!-- generated by tools/tier_agents/report.py; do not edit by hand -->\n")
    print("### Agent runs (Harbor, OpenCode 1.19.5): mean, then each run\n")
    print("Reference: campaign {campaign:.3f}, one site {traverse:.3f}.\n".format(**REFERENCE))
    print("| Tier | Model | Campaign (worlds 2027–2029) | One site (world 2026) |")
    print("|---|---|---|---|")
    for tier, models in LINEUP:
        for lab, name, stem in models:
            print("| {} | {} | {} | {} |".format(tier, name, cell(harbor_rewards("campaign-agent", stem)),
                                                 cell(harbor_rewards("traverse-agent", stem))))

    one = {}
    for _, models in LINEUP:
        for _, name, stem in models:
            one[name] = oneshot(stem)
    farm_one = farm_means(["programs-1", "programs-tiers"])
    camp_one = farm_means(["campaign-worlds", "campaign-worlds-tiers"])
    print("\n### One request, one program\n")
    print("| Tier | Model | World 2026 | 300 worlds (600–899) | Campaign worlds |")
    print("|---|---|---|---|---|")
    for tier, models in LINEUP:
        for _, name, stem in models:
            key = "program:traverse-oneshot-{}-1".format(stem)
            f, c = farm_one.get(key), camp_one.get(key)
            print("| {} | {} | {} | {} | {} |".format(tier, name, "–" if one[name] is None else "{:.3f}".format(one[name]),
                                                      "{:.3f}".format(f[0]) if f else "–", "{:.3f}".format(c[0]) if c else "–"))
    for label, table in (("300 worlds", farm_one), ("campaign worlds", camp_one)):
        if "pilot" in table:
            print("\nReference on the {}: {:.3f}.".format(label, table["pilot"][0]))

    farm_agent = farm_means(["programs-1", "programs-agents-tiers", "programs-agents-tiers-2"])
    camp_agent = farm_means(["campaign-worlds", "campaign-worlds-agents-tiers", "campaign-worlds-agents-tiers-2"])
    print("\n### Agents' own programs replayed (the world-2026 runs that left one)\n")
    print("| Model | Run | Live on 2026 | 300 worlds (600–899) | Campaign worlds |")
    print("|---|---|---|---|---|")
    for _, models in LINEUP:
        for _, name, stem in models:
            for folder in sorted(RUNS.glob("traverse-agent-{}-*".format(stem))):
                if not re.fullmatch(r"traverse-agent-{}-\d+".format(re.escape(stem)), folder.name):
                    continue
                key = "agent:" + folder.name
                f, c = farm_agent.get(key), camp_agent.get(key)
                if not f and not c:
                    continue
                live = harbor_rewards("traverse-agent", stem)[int(folder.name.rsplit("-", 1)[1]) - 1]
                print("| {} | {} | {:.3f} | {} | {} |".format(name, folder.name.rsplit("-", 1)[1], live,
                                                            "{:.3f}".format(f[0]) if f else "–", "{:.3f}".format(c[0]) if c else "–"))
    for label, table in (("300 worlds", farm_agent), ("campaign worlds", camp_agent)):
        if "pilot" in table:
            print("\nReference on the {}: {:.3f}.".format(label, table["pilot"][0]))

    spent = costs()
    print("\n### Cost per agent run (USD, OpenCode's count; GPT and Gemini only)\n")
    print("| Model | Runs | Mean | Total |")
    print("|---|---|---|---|")
    for _, models in LINEUP:
        for lab, name, stem in models:
            values = spent.get(stem)
            if values:
                print("| {} | {} | {:.2f} | {:.2f} |".format(name, len(values), statistics.mean(values), sum(values)))


if __name__ == "__main__":
    main()
