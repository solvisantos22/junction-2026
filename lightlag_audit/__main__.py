"""Audit saved Lightlag runs: which decisions lost points, why, and where the information was.

    python3 -m lightlag_audit docs/lightlag-runs/*/ --out docs/lightlag-audits

Writes <out>/<run>/audit.json and audit.md for every run folder, and <out>/README.md with one
row per run. Read-only on the run folders.
"""

import argparse
from pathlib import Path
import sys

from .counterfactual import REFERENCES
from .report import audit_run, write
from .runs import load_run


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python3 -m lightlag_audit", description=__doc__.splitlines()[0])
    parser.add_argument("runs", nargs="+", type=Path, help="run folders (artifacts/evaluator/replay.json inside)")
    parser.add_argument("--out", type=Path, default=Path("docs/lightlag-audits"))
    parser.add_argument("--reference", default="auto", choices=["auto", *REFERENCES],
                        help="who takes over at each decision (auto: team on core runs, kf_mpc on dynamic)")
    args = parser.parse_args(argv)
    rows, failures = [], 0
    for folder in args.runs:
        if not (folder / "artifacts" / "evaluator" / "replay.json").exists():
            continue
        try:
            run = load_run(folder)
            audit = audit_run(run, None if args.reference == "auto" else args.reference)
        except Exception as failure:  # one bad folder must not hide the others
            failures += 1
            print(f"{folder.name}: FAILED {type(failure).__name__}: {failure}", file=sys.stderr)
            continue
        write(audit, args.out / run.name)
        rows.append(audit)
        top = audit["main_mistakes"][0] if audit["main_mistakes"] else None
        print(f"{run.name}: agent {audit['score']['agent_raw']:g} vs reference {audit['score']['reference_raw']:g}"
              f" ({audit['reference']}); top: " +
              (f"{_tags(top)} −{top['points_lost']:g}" if top else "none") +
              f"; infra {len(audit['infrastructure'])}; rebuild {'ok' if audit['replay_matches'] else 'MISMATCH'}")
    if rows:
        _write_index(args.out, rows)
    return 1 if failures else 0


def _tags(item):
    return "/".join(dict.fromkeys(f["tag"] for f in item["findings"] if f["kind"] != "outcome")) or "?"


def _write_index(out, rows):
    lines = ["# Lightlag decision audits", "",
             "Generated by `python3 -m lightlag_audit` (see `docs/lightlag-audit.md`). One folder per run with "
             "`audit.md` (read this) and `audit.json`.", "",
             "| run | model | reference | agent | reference from start | gap (reward) | main mistakes | infrastructure | rebuild |",
             "|---|---|---|---:|---:|---:|---|---|---|"]
    for audit in sorted(rows, key=lambda a: a["run"]):
        score = audit["score"]
        main = "; ".join(f"call {m['n']} {_tags(m)} −{m['points_lost']:g}" if m["n"] is not None
                         else f"{_tags(m)} −{m['points_lost']:g}" for m in audit["main_mistakes"]) or "none"
        infra = ", ".join(f["tag"] for f in audit["infrastructure"]) or "none"
        lines.append(f"| [{audit['run']}]({audit['run']}/audit.md) | {audit['model'] or 'scripted'} | "
                     f"{audit['reference']} | {score['agent_raw']:g} | {score['reference_raw']:g} | "
                     f"{score['gap_reward']:.3f} | {main} | {infra} | {'ok' if audit['replay_matches'] else 'MISMATCH'} |")
    (out / "README.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main())
